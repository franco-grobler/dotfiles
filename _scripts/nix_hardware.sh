#!/usr/bin/env bash
# Regenerates this machine's hardware-configuration.nix (run on the linux host).
#
# Usage: nix_hardware.sh [host]
#
# On a fresh install the hostname is not the flake attribute yet, so pass the
# host explicitly: `just nix-hardware nixos-x8664`.
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${root}"

[[ "$(uname -s)" == "Linux" ]] || {
  echo "run this on the machine it describes" >&2
  exit 1
}
command -v nixos-generate-config >/dev/null || {
  echo "nixos-generate-config not found -- is this NixOS?" >&2
  exit 1
}

name="${1:-}"
if [[ -z ${name} ]]; then
  . ./_scripts/set_nix_envs.sh
  name="${NIXNAME}"
fi

dir="nix/modules/nixos/hosts/${name}"
[[ -d ${dir} ]] || {
  echo "no host directory at ${dir}" >&2
  echo "known hosts: $(ls nix/modules/nixos/hosts | tr '\n' ' ')" >&2
  exit 1
}

{
  echo '# Generated by `just nix-hardware`. Do not hand-edit -- rerun that recipe.'
  nixos-generate-config --show-hardware-config
} >"${dir}/hardware-configuration.nix"

echo "wrote ${dir}/hardware-configuration.nix"
git --no-pager diff --stat -- "${dir}/hardware-configuration.nix"
